// Reads data/episodes.txt and writes supabase/seed.sql (idempotent upserts).
// Edit the txt, rerun `npm run gen:episodes`, then run supabase/seed.sql again.
import { readFileSync, writeFileSync } from 'node:fs'

const esc = (s) => s.replace(/'/g, "''")
const rows = readFileSync('data/episodes.txt', 'utf8')
  .split('\n')
  .filter((l) => l.trim() && !l.startsWith('#'))
  .map((l) => {
    const [num, title, note = ''] = l.split('|')
    const [season, episode] = num.split('.').map(Number)
    return { season, episode, title: title.trim(), note: note.trim() }
  })

const values = rows
  .map(
    (r) =>
      `  (${r.season}, ${r.episode}, '${esc(r.title)}', ${r.note ? `'${esc(r.note)}'` : 'null'})`,
  )
  .join(',\n')

writeFileSync(
  'supabase/seed.sql',
  `-- GENERATED by scripts/gen-episodes.mjs from data/episodes.txt. Do not edit by hand.
-- verify_note is non-null for rows a human should double-check.
insert into public.episodes (season, episode, title, verify_note) values
${values}
on conflict (season, episode) do update
  set title = excluded.title, verify_note = excluded.verify_note;
`,
)
console.log(`wrote ${rows.length} episodes`)
